"""Curated 30-color realistic wardrobe palette (Core Neutrals + Statement/Accent)."""

from app.domain.color_math import hex_to_rgb, normalize_hex, rgb_to_hsl, rgb_to_lab
from app.domain.models import ColorToken, ColorValue, Undertone


def _make_token(
    token_id: str,
    name: str,
    hex_code: str,
    *,
    is_neutral: bool,
    undertone: Undertone,
    value: ColorValue,
    season_tags: tuple[str, ...],
) -> ColorToken:
    normalized = normalize_hex(hex_code)
    r, g, b = hex_to_rgb(normalized)
    return ColorToken(
        id=token_id,
        name=name,
        hex=normalized,
        hsl=rgb_to_hsl(r, g, b),
        lab=rgb_to_lab(r, g, b),
        is_neutral=is_neutral,
        undertone=undertone,
        value=value,
        season_tags=season_tags,
    )


